#!/usr/bin/env node
// Reads the Vite manifest, prints gzip sizes and enforces the Slice 14 budgets.
// `--write` also regenerates docs/bundle-report.md.
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { gzipSync } from "node:zlib";

const DIST = "dist";
const MANIFEST = join(DIST, ".vite", "manifest.json");
const REPORT = "docs/bundle-report.md";
const KB = 1024;

const BUDGETS = {
  entry: 350 * KB,
  route: 200 * KB,
  mapProvider: 500 * KB,
  css: 25 * KB,
};

function fail(message) {
  console.error(`BUNDLE FAIL: ${message}`);
  process.exitCode = 1;
}

if (!statSync(DIST, { throwIfNoEntry: false })?.isDirectory()) {
  fail("dist/ is missing; run vite build first");
  process.exit(1);
}

let manifest;
try {
  manifest = JSON.parse(readFileSync(MANIFEST, "utf8"));
} catch {
  fail("dist/.vite/manifest.json is missing; enable build.manifest in vite.config.ts");
  process.exit(1);
}

function measure(file) {
  const bytes = readFileSync(join(DIST, file));
  return { raw: bytes.length, gzip: gzipSync(bytes, { level: 9 }).length };
}

function format(bytes) {
  return `${(bytes / KB).toFixed(1)} KB`;
}

const chunks = new Map();
function remember(file) {
  if (!file || chunks.has(file)) return chunks.get(file);
  const size = measure(file);
  chunks.set(file, size);
  return size;
}

const entryRecord = manifest["index.html"];
if (!entryRecord) fail("manifest has no index.html entry");

let entryGzip = 0;
const entryFiles = [];
if (entryRecord) {
  entryFiles.push(entryRecord.file);
  entryGzip += remember(entryRecord.file).gzip;
  for (const key of entryRecord.imports ?? []) {
    const imported = manifest[key];
    if (!imported) continue;
    entryFiles.push(imported.file);
    entryGzip += remember(imported.file).gzip;
  }
}

const routes = Object.entries(manifest)
  .filter(([key]) => key.startsWith("src/features/") && key.endsWith("Page.tsx"))
  .map(([, record]) => ({ name: record.name ?? record.file, ...remember(record.file) }))
  .sort((a, b) => b.gzip - a.gzip);

const largestRoute = routes[0];

const assets = readdirSync(join(DIST, "assets"));
const mapProviderFiles = assets.filter(
  (file) => /^maplibre-.*\.js$/.test(file) && !/^maplibre-gl-worker-.*\.js$/.test(file),
);
const workerFiles = assets.filter((file) => /^maplibre-gl-worker-.*\.js$/.test(file));
const mapProviderGzip = [...mapProviderFiles, ...workerFiles].reduce(
  (total, file) => total + remember(`assets/${file}`).gzip,
  0,
);

const cssFiles = assets.filter((file) => file.endsWith(".css"));
const cssGzip = cssFiles.reduce((total, file) => total + remember(`assets/${file}`).gzip, 0);

const checks = [
  {
    name: "Entry chunk",
    actual: entryGzip,
    budget: BUDGETS.entry,
    detail: entryFiles.join(", "),
  },
  {
    name: "Largest route chunk",
    actual: largestRoute?.gzip ?? 0,
    budget: BUDGETS.route,
    detail: largestRoute?.name ?? "none",
  },
  {
    name: "MapLibre provider + worker",
    actual: mapProviderGzip,
    budget: BUDGETS.mapProvider,
    detail: [...mapProviderFiles, ...workerFiles].join(", "),
  },
  {
    name: "CSS",
    actual: cssGzip,
    budget: BUDGETS.css,
    detail: cssFiles.join(", "),
  },
];

const rows = [
  ["Entry (static graph)", entryGzip],
  ...routes.map((route) => [`Route · ${route.name}`, route.gzip]),
  ["MapLibre provider", remember(`assets/${mapProviderFiles[0]}`)?.gzip ?? 0],
  ...workerFiles.map((file) => ["MapLibre worker", remember(`assets/${file}`).gzip]),
  ["CSS", cssGzip],
];

const table = [
  "| Bundle | Gzip | Budget | Result |",
  "| --- | ---: | ---: | --- |",
  ...checks.map((check) => {
    const over = check.actual > check.budget;
    return `| ${check.name} | ${format(check.actual)} | ${format(check.budget)} | ${over ? "OVER" : "pass"} |`;
  }),
  "",
  "| Chunk | Gzip |",
  "| --- | ---: |",
  ...rows.map(([name, gzip]) => `| ${name} | ${format(gzip)} |`),
].join("\n");

console.log(table);

for (const check of checks) {
  if (check.actual > check.budget) {
    fail(
      `${check.name} is ${format(check.actual)} gzip (${check.detail}), over the ${format(check.budget)} budget`,
    );
  }
}

if (process.argv.includes("--write")) {
  const report = [
    "# Bundle report",
    "",
    "Generated by `npm run bundle:report` from `dist/.vite/manifest.json` after a production build.",
    "Budgets are enforced by the same script and by `npm run build`.",
    "",
    table,
    "",
  ].join("\n");
  writeFileSync(REPORT, report);
  console.log(`bundle-report: wrote ${REPORT}`);
}
