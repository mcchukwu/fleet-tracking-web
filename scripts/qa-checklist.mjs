#!/usr/bin/env node
// Turns test-results/review/*.png into docs/qa-checklist.md, grouped by screen.
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const REVIEW_DIR = join("test-results", "review");
const OUTPUT = "docs/qa-checklist.md";

if (!existsSync(REVIEW_DIR)) {
  console.error(`Cannot read ${REVIEW_DIR}. Run npm run e2e:review first.`);
  process.exit(1);
}

const files = readdirSync(REVIEW_DIR)
  .filter((file) => file.endsWith(".png"))
  .sort();

const shots = files.map((file) => {
  const stem = file.slice(0, -".png".length);
  const parts = stem.split("-");
  const viewport = parts.pop() ?? "unknown";
  const theme = parts.pop() ?? "unknown";
  const name = parts.join("-");
  const [screen = "other", ...stateParts] = name.split("-");
  return { file, screen, state: stateParts.join("-") || "ready", theme, viewport, name };
});

const screens = [...new Set(shots.map((shot) => shot.screen))].sort((a, b) => a.localeCompare(b));
const lines = [
  "# Human QA checklist",
  "",
  "Generated by `npm run qa:checklist` from `captureForReview` output in `test-results/review/`.",
  "The agent cannot see images. These are the screenshots a human must review; nothing here claims visual approval.",
  "",
  "For every screenshot, check: sentence case and tone (design-system §8), hierarchy (§2), spacing rhythm and density (§3),",
  "contrast, focus visibility, tabular numbers, mono identifiers, `—` for missing values, and that nothing overlaps or clips.",
  "",
];

for (const screen of screens) {
  const rows = shots.filter((shot) => shot.screen === screen);
  lines.push(`## ${screen[0]?.toUpperCase() ?? ""}${screen.slice(1)}`, "");
  lines.push("| State | Theme | Viewport | Screenshot | Reviewed |");
  lines.push("| --- | --- | --- | --- | --- |");
  for (const row of rows) {
    lines.push(
      `| ${row.state} | ${row.theme} | ${row.viewport} | \`test-results/review/${row.file}\` | [ ] |`,
    );
  }
  lines.push("");
}

const themes = new Set(shots.map((shot) => shot.theme));
const viewports = new Set(shots.map((shot) => shot.viewport));
lines.push(
  `Total: ${shots.length} screenshots across ${screens.length} screens, ${[...themes].sort((a, b) => a.localeCompare(b)).join("/")} themes and ${[...viewports].sort((a, b) => a.localeCompare(b)).join(", ")} viewports.`,
  "",
  "Also review `/styleguide` in light and dark with all four accents: it is the visual contract, not a feature screen.",
  "",
);

writeFileSync(OUTPUT, lines.join("\n"));
console.log(
  `qa-checklist: ${shots.length} screenshots from ${screens.length} screens -> ${OUTPUT}`,
);
